const STORE_KEY = "aimforge.lang";

function apply(lang) {
  const table = TEXT[lang] || TEXT.de;
  document.documentElement.lang = lang;
  document.title = table["meta.title"];

  const desc = document.querySelector('meta[name="description"]');
  if (desc) desc.setAttribute("content", table["meta.desc"]);

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.getAttribute("data-i18n");
    const value = table[key];
    if (value === undefined) return;
    if (/<[a-z/]/i.test(value)) node.innerHTML = value;
    else node.textContent = value;
  });

  document.querySelectorAll(".lang").forEach((chip) => {
    chip.setAttribute("aria-pressed", String(chip.dataset.lang === lang));
  });

  try {
    localStorage.setItem(STORE_KEY, lang);
  } catch (error) {
    /* private mode: just skip persistence */
  }
}

document.querySelectorAll(".lang").forEach((chip) => {
  chip.addEventListener("click", () => apply(chip.dataset.lang));
});

/* A soft ring on every click, the same gesture as the app. */
document.querySelectorAll(".btn").forEach((button) => {
  button.addEventListener("pointerdown", (event) => {
    const rect = button.getBoundingClientRect();
    const size = Math.max(rect.width, rect.height) * 2.2;
    const ring = document.createElement("span");
    ring.className = "ripple";
    ring.style.width = ring.style.height = `${size}px`;
    ring.style.left = `${event.clientX - rect.left}px`;
    ring.style.top = `${event.clientY - rect.top}px`;
    button.appendChild(ring);
    ring.addEventListener("animationend", () => ring.remove());
  });
});

let saved = "de";
try {
  saved = localStorage.getItem(STORE_KEY) || "de";
} catch (error) {
  saved = "de";
}
/* Honour a ?lang=en link on first visit. */
const fromUrl = new URLSearchParams(window.location.search).get("lang");
apply((fromUrl || saved) === "en" ? "en" : "de");
